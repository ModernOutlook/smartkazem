  function render() {
    const language = window.SiteI18n?.getLanguage?.() || document.documentElement.lang || 'fa';
    const catalog = window.SiteI18n?.getCatalog?.()?.bookContent?.zero;
    const title = language === 'fa' ? window.ZeroPersianSource.title : catalog?.title?.[language];
    const paragraphs = language === 'fa' ? window.ZeroPersianSource.paragraphs : catalog?.paragraphs?.[language];
    if (!Array.isArray(paragraphs) || !title) return;

    const heading = document.getElementById('zero-title');
    const article = document.getElementById('zero-story');
    if (!heading || !article) return;
    heading.textContent = title;
    article.replaceChildren(...paragraphs.map((text) => {
      const paragraph = document.createElement('p');
      paragraph.textContent = text;
      return paragraph;
    }));
    article.lang = language;
    article.dir = ['fa', 'ar'].includes(language) ? 'rtl' : 'ltr';
  }

  document.addEventListener('site:languagechange', render);
